INTERNAL_CATEGORIES_FILE = "internal_categories.yaml"
CATEGORY_KEY_RE = re.compile(r"^[a-z][a-z0-9-]{1,63}$")


def load_internal_categories(repo: Path) -> tuple[list[dict[str, str]], dict[str, str], list[str]]:
    """(categories, {skill id: category key}, problems) from ``internal_categories.yaml``.

    The keys are the online market's, so the internal library and the market are searched by one set of
    categories. A missing file files nothing; a listed skill that is not in the library, or a key that is not
    a listed category, is a problem the distribution check reports.
    """
    path = Path(repo) / CATALOG_DIR / INTERNAL_CATEGORIES_FILE
    problems: list[str] = []
    if not path.is_file():
        return [], {}, problems
    data = _read_yaml(path, problems)
    if not isinstance(data, dict):
        return [], {}, problems or [f"{INTERNAL_CATEGORIES_FILE}: expected a mapping"]
    categories: list[dict[str, str]] = []
    raw_categories = data.get("categories") or []
    if not isinstance(raw_categories, list):
        problems.append(f"{INTERNAL_CATEGORIES_FILE}: categories must be a list of {{key, name}}")
        raw_categories = []
    for item in raw_categories:
        key = str((item or {}).get("key") or "") if isinstance(item, dict) else ""
        if not CATEGORY_KEY_RE.match(key) or not str(item.get("name") or "").strip():
            problems.append(f"{INTERNAL_CATEGORIES_FILE}: a category needs a key (lowercase, digits, -) and a name: {item!r}"[:200])
            continue
        if any(category["key"] == key for category in categories):
            problems.append(f"{INTERNAL_CATEGORIES_FILE}: category {key} is listed twice")
            continue
        categories.append({"key": key, "name": str(item["name"]).strip(), "name_en": str(item.get("name_en") or "").strip()})
    keys = {category["key"] for category in categories}
    skills_root = Path(repo) / "distribution" / "skills"
    filed: dict[str, str] = {}
    raw_skills = data.get("skills") or {}
    if not isinstance(raw_skills, dict):
        problems.append(f"{INTERNAL_CATEGORIES_FILE}: skills must map a skill id to a category key")
        raw_skills = {}
    for skill_id, key in raw_skills.items():
        skill_id, key = str(skill_id), str(key or "")
        if key not in keys:
            problems.append(f"{INTERNAL_CATEGORIES_FILE}: skill {skill_id} is filed under {key!r}, which is not a listed category")
            continue
        if not ID_RE.match(skill_id) or not (skills_root / skill_id / "SKILL.md").is_file():
            problems.append(f"{INTERNAL_CATEGORIES_FILE}: skill {skill_id} is not in distribution/skills")
            continue
        filed[skill_id] = key
    return categories, filed, problems


def internal_skills(
    skills_root: Path, packages: list[Any], categories: dict[str, str] | None = None, *, project_id: str | None = None,
) -> list[dict[str, Any]]:
    """The shared skills a workflow package may declare, with who uses them.

    Being here means a skill can be declared; a release contract (version,
    provenance, tests, success criteria) is what lets a testing or published
    package lock it, and that is reported per skill rather than assumed.
    A skill admitted from the market keeps the market's category (from its
    ADMISSION.json); our own are filed by ``categories``.

    With ``project_id``, "who uses them" leaves out the flows another project owns (usable_by_project): one project
    is one customer, and the names of another customer's flows are not listed to this one. ``None`` lists every flow.
    """
    from ampuly.plugins.office_ui.workflow_packages import load_skill_contract, usable_by_project

    if project_id is not None:
        packages = [package for package in packages if usable_by_project(package, project_id)]
    root = Path(skills_root)
    if not root.is_dir():
        return []
    resolved = root.resolve()
    rows: list[dict[str, Any]] = []
    for folder in sorted(root.iterdir(), key=lambda item: item.name):
        skill_md = folder / "SKILL.md"
        if not folder.is_dir() or _is_link(folder) or not skill_md.is_file():
            continue
        front = _frontmatter(skill_md.read_text(encoding="utf-8", errors="replace")) or {}
        contract = load_skill_contract(root, folder.name)
        admission: dict[str, Any] | None = None
        record_path = folder / "ADMISSION.json"
        if record_path.is_file():
            # A skill admitted from the market says where it came from and who let it in.
            try:
                record = json.loads(record_path.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                record = {}
            source = record.get("source") if isinstance(record, dict) and isinstance(record.get("source"), dict) else {}
            admission = {
                "category": str(source.get("category") or ""),
                "market": str(source.get("market") or ""),
                "slug": str(source.get("slug") or ""),
                "version": str(source.get("version") or ""),
                "admitted_by": str(record.get("admitted_by") or "") if isinstance(record, dict) else "",
                "admitted_at": str(record.get("admitted_at") or "") if isinstance(record, dict) else "",
            }
        rows.append({
            "admission": admission,
            "category": str((admission or {}).get("category") or (categories or {}).get(folder.name) or ""),
            "id": folder.name,
            "name": str(front.get("display_name") or front.get("name") or folder.name),
            "summary": _summary(front.get("description")),
            "version": contract.version,
            "contract_complete": contract.complete,
            "problems": list(contract.problems),
            "used_by": [
                {"id": str(package.id), "name": str(package.name), "status": str(package.status)}
                for package in packages
                if folder.name in package.skills and Path(package.skills_root).resolve() == resolved
            ],
        })
    return rows


