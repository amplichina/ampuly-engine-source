def _read_yaml(path: Path, problems: list[str]) -> Any:
    try:
        return yaml.safe_load(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, yaml.YAMLError) as exc:
        problems.append(f"{path.name}: unreadable ({str(exc).splitlines()[0] if str(exc) else type(exc).__name__})")
        return None


def load_catalog(repo: Path) -> ComponentCatalog:
    """Both catalog files, validated.  A missing file is an empty section, not a problem."""
    catalog = ComponentCatalog()
    root = Path(repo) / CATALOG_DIR
    connectors_path = root / CONNECTORS_FILE
    if connectors_path.is_file():
        data = _read_yaml(connectors_path, catalog.problems)
        if data is not None:
            found = validate_connector_catalog(data)
            catalog.problems.extend(found)
            if isinstance(data, dict):
                catalog.domains = [dict(item) for item in data.get("domains") or [] if isinstance(item, dict)]
                catalog.tooling = [dict(item) for item in data.get("tooling") or [] if isinstance(item, dict)]
                catalog.planned = [dict(item) for item in data.get("planned") or [] if isinstance(item, dict)]
                catalog.connectors = [dict(item) for item in data.get("connectors") or [] if isinstance(item, dict)]
    skills_path = root / SKILLS_FILE
    if skills_path.is_file():
        data = _read_yaml(skills_path, catalog.problems)
        if data is not None:
            catalog.problems.extend(validate_skill_catalog(data))
            if isinstance(data, dict):
                catalog.skills = [dict(item) for item in data.get("skills") or [] if isinstance(item, dict)]
                catalog.library = str(data.get("library") or "")
    return catalog
