def risk_from_reasons(reasons: list[str], table: dict[str, str]) -> str:
    levels = [table[reason] for reason in reasons if reason in table]
    if not levels:
        return "low"
    return max(levels, key=lambda level: RISK_ORDER[level])


def connector_payload(entry: dict[str, Any]) -> dict[str, Any]:
    governance = dict(entry.get("governance") or {})
    capability = dict(entry.get("capability") or {})
    risk = str(governance.get("risk_level", ""))
    payload = {
        "id": entry.get("id"),
        "name": entry.get("name"),
        "name_en": entry.get("name_en") or "",
        "domain": entry.get("domain"),
        "group": entry.get("group") or "",
        "access_mode": entry.get("access_mode"),
        "install": dict(entry.get("install") or {}),
        "config_schema": [dict(item) for item in entry.get("config_schema") or []],
        # None means the source list does not say; admission has to find out.
        "capability": {
            "summary": capability.get("summary", ""),
            "readonly": capability.get("readonly"),
            "side_effects": capability.get("side_effects"),
        },
        # 治理规则 §二 凭据隔离, §五 预算护栏 and §六 审计留痕 hold for every
        # connector whatever executes it; they are stated, not configurable.
        "governance": {
            "risk_level": risk,
            "reasons": list(governance.get("reasons") or []),
            "credential_isolation": True,
            "audit_required": True,
            "budget_guard": True,
            "extra_human_review": risk == "high",
            "rules": "browser" if entry.get("access_mode") == "browser" else "api",
        },
        "pricing": dict(entry.get("pricing") or {}),
        "source": dict(entry.get("source") or {}),
        "inferred": list(entry.get("inferred") or []),
        "notes": list(entry.get("notes") or []),
        "admission": "catalogued",
    }
    payload["admission_plan"] = connector_admission_plan(entry)
    return payload


def connector_admission_plan(entry: dict[str, Any]) -> dict[str, Any]:
    """Compile catalog facts into the existing connector-governance route.

    This is an admission *plan*, not admission.  It makes every missing proof
    explicit before M3 generates a candidate, and fixes the isolation/audit
    rules that no candidate or UI may relax.
    """
    governance = dict(entry.get("governance") or {})
    capability = dict(entry.get("capability") or {})
    config = [dict(item) for item in list(entry.get("config_schema") or []) if isinstance(item, dict)]
    access_mode = str(entry.get("access_mode") or "")
    risk = str(governance.get("risk_level") or "low")
    blockers: list[str] = []
    required_evidence = [
        "implementation_identity", "tool_inventory", "scope_probe",
        "credential_reference", "budget_limits", "audit_sink", "contract_tests",
    ]
    if list(entry.get("inferred") or []):
        blockers.append("inferred_fields_need_review")
    if capability.get("readonly") is None or capability.get("side_effects") is None:
        blockers.append("capability_classification_missing")
    if not (dict(entry.get("source") or {}).get("repo") or dict(entry.get("source") or {}).get("local_path")):
        blockers.append("implementation_source_missing")
    if any(bool(item.get("required")) for item in config):
        required_evidence.append("configuration_shape_check")
    if dict(entry.get("pricing") or {}):
        required_evidence.append("cost_probe")
    if risk == "high":
        required_evidence.extend(["negative_side_effect_probe", "owner_risk_review"])
    route = {
        "existing_mcp": "inspect_existing_mcp",
        "fastmcp_wrap": "generate_declarative_candidate",
        "browser": "computer_use_candidate",
        "commercial": "vendor_connector_review",
    }.get(access_mode, "unsupported")
    if access_mode == "browser":
        required_evidence.append("computer_use_conformance")
    if access_mode == "commercial":
        required_evidence.append("vendor_terms_and_health")
    canonical = json.dumps(entry, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return {
        "catalog_fingerprint": hashlib.sha256(canonical.encode("utf-8")).hexdigest(),
        "route": route,
        "state": "blocked" if blockers else "ready_for_candidate",
        "blockers": blockers,
        "required_evidence": list(dict.fromkeys(required_evidence)),
        "enforced": {
            "credential_values_in_registry": False,
            "workspace_scope_required": True,
            "audit_required": True,
            "budget_required": True,
            "human_review_required": risk == "high",
            "activation_after_registration": False,
        },
    }


def resolve_connector_admission(
    entry: dict[str, Any],
    *,
    contract_source: str,
    confirmed_inferred_fields: list[str] | None = None,
) -> dict[str, Any]:
    """Resolve only evidence supplied by a formal candidate contract.

    A source citation can satisfy the missing-implementation-source blocker.
    Inferred catalog facts remain blocked unless the owner explicitly confirms
    their exact field names; a model-authored contract cannot confirm them.
    """

    plan = connector_admission_plan(entry)
    blockers = list(plan["blockers"])
    if str(contract_source or "").strip():
        blockers = [item for item in blockers if item != "implementation_source_missing"]
    confirmed = {str(item or "").strip() for item in list(confirmed_inferred_fields or [])}
    inferred = {str(item or "").strip() for item in list(entry.get("inferred") or [])}
    if inferred and inferred <= confirmed:
        blockers = [item for item in blockers if item != "inferred_fields_need_review"]
    return {**plan, "blockers": blockers, "state": "blocked" if blockers else "ready_for_candidate"}


def attach_connector_lifecycle(
    payload: dict[str, Any],
    candidates: list[dict[str, Any]],
    registrations: list[dict[str, Any]],
) -> dict[str, Any]:
    """Join project lifecycle facts only when they carry this catalog fingerprint.

    A matching connector name is not evidence: custom candidates may reuse a
    name.  The catalog id and the exact catalog bytes must both be bound into
    candidate provenance before the external-library card may claim progress.
    """

    for connector in list(payload.get("connectors") or []):
        if not isinstance(connector, dict):
            continue
        plan = dict(connector.get("admission_plan") or {})
        catalog_id = str(connector.get("id") or "")
        fingerprint = str(plan.get("catalog_fingerprint") or "")

        def bound(row: dict[str, Any]) -> bool:
            admission = dict(row.get("catalog_admission") or {})
            return (
                str(admission.get("catalog_id") or "") == catalog_id
                and str(admission.get("catalog_fingerprint") or "") == fingerprint
            )

        related = [dict(row) for row in candidates if isinstance(row, dict) and bound(row)]
        related.sort(key=lambda row: str(row.get("created_at") or ""), reverse=True)
        registered = [dict(row) for row in registrations if isinstance(row, dict) and bound(row)]
        registered.sort(key=lambda row: str(row.get("registered_at") or ""), reverse=True)
        latest_candidate = related[0] if related else None
        latest_registration = registered[0] if registered else None
        connector["lifecycle"] = {
            "stage": (
                str(latest_registration.get("status") or "registered")
                if latest_registration else
                str(latest_candidate.get("status") or "catalogued")
                if latest_candidate else "catalogued"
            ),
            "candidate": latest_candidate,
            "registration": latest_registration,
        }
    return payload


def _machine_paths(node: Any, where: str, problems: list[str]) -> None:
    if isinstance(node, dict):
        for key, value in node.items():
            _machine_paths(value, f"{where}.{key}", problems)
    elif isinstance(node, list):
        for index, item in enumerate(node):
            _machine_paths(item, f"{where}[{index}]", problems)
    elif isinstance(node, str) and MACHINE_PATH_RE.search(node):
        problems.append(f"{where}: machine path in the catalog ({node[:40]})")


def _relative_library_path(value: Any) -> bool:
    text = str(value or "")
    if not text or "\\" in text or MACHINE_PATH_RE.search(text):
        return False
    path = PurePosixPath(text)
    return not path.is_absolute() and ".." not in path.parts


def validate_connector(entry: Any, *, domains: set[str], source_lists: set[str]) -> list[str]:
    if not isinstance(entry, dict):
        return ["connector entry must be a mapping"]
    label = f"connector {entry.get('id') or '?'}"
    problems: list[str] = []
    unknown = sorted(set(entry) - CONNECTOR_KEYS)
    if unknown:
        problems.append(f"{label}: unknown field(s) {', '.join(unknown)}")
    if not ID_RE.match(str(entry.get("id") or "")):
        problems.append(f"{label}: id must be lowercase letters, digits, '.', '_' or '-'")
    for key in ("name", "group"):
        if not isinstance(entry.get(key), str) or not entry[key].strip():
            problems.append(f"{label}: {key} must be a non-empty string")
    if entry.get("domain") not in domains:
        problems.append(f"{label}: domain {entry.get('domain')!r} is not a catalog domain")
    if entry.get("access_mode") not in ACCESS_MODES:
        problems.append(f"{label}: access_mode must be one of {', '.join(ACCESS_MODES)}")

    install = entry.get("install")
    if install is not None and not (isinstance(install, dict) and isinstance(install.get("type"), str) and install["type"].strip()):
        problems.append(f"{label}: install must be a mapping with a type")

    config = entry.get("config_schema")
    if config is not None:
        if not isinstance(config, list):
            problems.append(f"{label}: config_schema must be a list")
        else:
            seen: set[str] = set()
            for item in config:
                if not isinstance(item, dict) or set(item) - {"key", "secret", "required"}:
                    problems.append(f"{label}: config items are {{key, secret, required}} -- names only, never values")
                    continue
                key = str(item.get("key") or "")
                if not CONFIG_KEY_RE.match(key):
                    problems.append(f"{label}: config key {key!r} is not a plain name")
                if key in seen:
                    problems.append(f"{label}: config key {key} is listed twice")
                seen.add(key)
                if not isinstance(item.get("secret"), bool) or not isinstance(item.get("required"), bool):
                    problems.append(f"{label}: config key {key}: secret and required must be true or false")
                if SECRET_CONFIG_KEY_RE.search(key) and item.get("secret") is not True:
                    problems.append(f"{label}: config key {key} names a credential and must be secret: true")

    capability = entry.get("capability")
    if not isinstance(capability, dict) or not isinstance(capability.get("summary"), str) or not capability["summary"].strip():
        problems.append(f"{label}: capability needs a summary")
    else:
        if set(capability) - {"summary", "readonly", "side_effects"}:
            problems.append(f"{label}: capability has unknown field(s)")
        readonly = capability.get("readonly")
        effects = capability.get("side_effects")
        if readonly is not None and not isinstance(readonly, bool):
            problems.append(f"{label}: capability.readonly must be true, false or absent")
        if effects is not None:
            if not isinstance(effects, list) or any(effect not in SIDE_EFFECTS for effect in effects):
                problems.append(f"{label}: side_effects must come from {', '.join(sorted(SIDE_EFFECTS))}")
            elif readonly is True and effects:
                problems.append(f"{label}: a read-only connector cannot declare side effects")

    governance = entry.get("governance")
    if not isinstance(governance, dict):
        problems.append(f"{label}: governance is required")
    else:
        if set(governance) - {"risk_level", "reasons"}:
            problems.append(f"{label}: governance carries risk_level and reasons only; the hard rules are not per-entry options")
        reasons = governance.get("reasons")
        if not isinstance(reasons, list) or not reasons or any(reason not in CONNECTOR_RISK_REASONS for reason in reasons):
            problems.append(f"{label}: governance.reasons must be a non-empty list from {', '.join(sorted(CONNECTOR_RISK_REASONS))}")
        elif governance.get("risk_level") != risk_from_reasons(reasons, CONNECTOR_RISK_REASONS):
            problems.append(
                f"{label}: risk_level {governance.get('risk_level')!r} does not follow from its reasons "
                f"(expected {risk_from_reasons(reasons, CONNECTOR_RISK_REASONS)!r})"
            )

    pricing = entry.get("pricing")
    if pricing is not None and not (isinstance(pricing, dict) and pricing.get("model") in PRICING_MODELS and set(pricing) <= {"model", "hint"}):
        problems.append(f"{label}: pricing must be {{model: {'|'.join(PRICING_MODELS)}, hint}}")

    source = entry.get("source")
    if source is not None:
        if not isinstance(source, dict) or set(source) - {"local_path", "repo", "list"}:
            problems.append(f"{label}: source carries local_path, repo and list only")
        else:
            if "local_path" in source and not _relative_library_path(source["local_path"]):
                problems.append(f"{label}: source.local_path must be relative to the connector library")
            if "repo" in source and not REPO_RE.match(str(source["repo"])):
                problems.append(f"{label}: source.repo must be owner/name")
            if "list" in source and source["list"] not in source_lists:
                problems.append(f"{label}: source.list {source['list']!r} is not one of the catalog's sources")

    inferred = entry.get("inferred")
    if inferred is not None and (not isinstance(inferred, list) or any(item not in INFERABLE_FIELDS for item in inferred)):
        problems.append(f"{label}: inferred may only name {', '.join(sorted(INFERABLE_FIELDS))}")
    notes = entry.get("notes")
    if notes is not None and (not isinstance(notes, list) or any(not isinstance(note, str) or not note.strip() for note in notes)):
        problems.append(f"{label}: notes must be a list of strings")
    return problems


def validate_connector_catalog(data: Any) -> list[str]:
    if not isinstance(data, dict):
        return ["connectors.yaml must be a mapping"]
    problems: list[str] = []
    if data.get("schema_version") != SCHEMA_VERSION:
        problems.append(f"connectors.yaml: schema_version must be {SCHEMA_VERSION}")
    domain_ids: set[str] = set()
    for domain in data.get("domains") or []:
        if not isinstance(domain, dict) or not ID_RE.match(str(domain.get("id") or "")) or not str(domain.get("name") or "").strip():
            problems.append("connectors.yaml: every domain needs an id and a name")
            continue
        if domain["id"] in domain_ids:
            problems.append(f"connectors.yaml: domain {domain['id']} is listed twice")
        domain_ids.add(domain["id"])
    sources = data.get("sources") if isinstance(data.get("sources"), dict) else {}
    entries = data.get("connectors")
    if not isinstance(entries, list) or not entries:
        problems.append("connectors.yaml: connectors must be a non-empty list")
        entries = []
    seen: set[str] = set()
    for entry in entries:
        problems.extend(validate_connector(entry, domains=domain_ids, source_lists=set(sources)))
        entry_id = entry.get("id") if isinstance(entry, dict) else None
        if entry_id in seen:
            problems.append(f"connector {entry_id}: id is listed twice")
        seen.add(entry_id)
    for section in ("tooling", "planned"):
        for item in data.get(section) or []:
            if not isinstance(item, dict) or not ID_RE.match(str(item.get("id") or "")) or not str(item.get("name") or "").strip():
                problems.append(f"connectors.yaml: every {section} item needs an id and a name")
            elif item["id"] in seen:
                problems.append(f"connectors.yaml: {section} item {item['id']} reuses a connector id")
    _machine_paths(data, "connectors.yaml", problems)
    return problems


