def skill_governance(entry: dict[str, Any]) -> dict[str, Any]:
    requires = entry.get("requires") or {}
    pricing = entry.get("pricing") or {}
    license_info = entry.get("license") or {}
    reasons: list[str] = []
    if pricing.get("paid"):
        reasons.append("per_use_payment")
    if any(SHELL_TOOL_RE.match(tool) for tool in requires.get("tools") or []):
        reasons.append("shell_access")
    if entry.get("code_files") or entry.get("dependency_manifests") or entry.get("file_walk_truncated"):
        reasons.append("bundled_code")
    if requires.get("env"):
        reasons.append("needs_credentials")
    if requires.get("bins"):
        reasons.append("external_programs")
    blockers: list[str] = []
    if license_info.get("class") == "restricted":
        blockers.append("license_restricts_redistribution")
    elif license_info.get("class") != "permissive":
        blockers.append("license_unconfirmed")
    if pricing.get("paid"):
        blockers.append("owner_budget_approval")
    if not entry.get("frontmatter"):
        blockers.append("frontmatter_missing")
    return {
        "risk_level": risk_from_reasons(reasons, SKILL_RISK_REASONS),
        "reasons": reasons,
        "admission_blockers": blockers,
    }


def skill_payload(entry: dict[str, Any]) -> dict[str, Any]:
    return {**entry, "governance": skill_governance(entry), "admission": "catalogued"}


SKILL_KEYS = frozenset({
    "id", "name", "name_en", "version", "category", "summary", "source", "frontmatter", "agent_created",
    "requires", "bundles", "code_files", "dependency_manifests", "license", "pricing", "file_walk_truncated",
})


def validate_skill(entry: Any) -> list[str]:
    if not isinstance(entry, dict):
        return ["skill entry must be a mapping"]
    label = f"skill {entry.get('id') or '?'}"
    problems: list[str] = []
    unknown = sorted(set(entry) - SKILL_KEYS)
    if unknown:
        problems.append(f"{label}: unknown field(s) {', '.join(unknown)} (the catalog keeps metadata only)")
    if not isinstance(entry.get("id"), str) or not entry["id"].strip() or "/" in entry["id"] or "\\" in entry["id"]:
        problems.append(f"{label}: id must be the skill's folder name")
    if not isinstance(entry.get("name"), str) or not entry["name"].strip():
        problems.append(f"{label}: name is required")
    if len(str(entry.get("summary") or "")) > SUMMARY_LIMIT:
        problems.append(f"{label}: summary is longer than {SUMMARY_LIMIT} characters -- the catalog is not a copy of the skill")
    source = entry.get("source")
    if not isinstance(source, dict) or not _relative_library_path(source.get("path")):
        problems.append(f"{label}: source.path must be relative to the skill library")
    elif not re.fullmatch(r"[0-9a-f]{64}", str(source.get("skill_md_sha256") or "")):
        problems.append(f"{label}: source.skill_md_sha256 must be a sha256 digest")
    license_info = entry.get("license")
    if not isinstance(license_info, dict) or license_info.get("class") not in {"permissive", "restricted", "unknown"}:
        problems.append(f"{label}: license.class must be permissive, restricted or unknown")
    pricing = entry.get("pricing")
    if not isinstance(pricing, dict) or not isinstance(pricing.get("paid"), bool):
        problems.append(f"{label}: pricing.paid must be true or false")
    requires = entry.get("requires")
    if not isinstance(requires, dict) or any(not isinstance(requires.get(key), list) for key in ("tools", "bins", "env")):
        problems.append(f"{label}: requires must list tools, bins and env")
    return problems


def validate_skill_catalog(data: Any) -> list[str]:
    if not isinstance(data, dict):
        return ["skills.yaml must be a mapping"]
    problems: list[str] = []
    if data.get("schema_version") != SCHEMA_VERSION:
        problems.append(f"skills.yaml: schema_version must be {SCHEMA_VERSION}")
    entries = data.get("skills")
    if not isinstance(entries, list):
        return [*problems, "skills.yaml: skills must be a list"]
    seen: set[str] = set()
    for entry in entries:
        problems.extend(validate_skill(entry))
        entry_id = entry.get("id") if isinstance(entry, dict) else None
        if entry_id in seen:
            problems.append(f"skill {entry_id}: id is listed twice")
        seen.add(entry_id)
    _machine_paths(data, "skills.yaml", problems)
    return problems


