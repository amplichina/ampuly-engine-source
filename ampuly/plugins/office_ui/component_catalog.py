def _frontmatter(text: str) -> dict[str, Any] | None:
    match = re.match(r"^﻿?---[ \t]*\r?\n(.*?)\r?\n---[ \t]*(\r?\n|$)", text, re.S)
    if not match:
        return None
    try:
        data = yaml.safe_load(match.group(1))
    except yaml.YAMLError:
        return None
    return data if isinstance(data, dict) else None


def _summary(text: Any) -> str:
    flat = " ".join(str(text or "").split())
    if not flat:
        return ""
    end = re.search(r"[。！？!?]|\.(\s|$)", flat)
    if end and end.end() <= SUMMARY_LIMIT:
        return flat[: end.end()].strip()
    return flat if len(flat) <= SUMMARY_LIMIT else flat[: SUMMARY_LIMIT - 1].rstrip() + "…"


def _is_link(path: Path) -> bool:
    if path.is_symlink():
        return True
    is_junction = getattr(path, "is_junction", None)  # Python 3.12+
    if callable(is_junction):
        return bool(is_junction())
    try:
        info = path.lstat()
    except OSError:
        return False
    # Python 3.10/3.11 on Windows: a junction is a mount-point reparse point, which islink() does not see. Only that
    # tag -- the broad reparse-point attribute is also set on cloud placeholders and deduplicated files.
    return getattr(info, "st_reparse_tag", 0) == getattr(stat, "IO_REPARSE_TAG_MOUNT_POINT", 0xA0000003)


def _string_list(value: Any) -> list[str]:
    if isinstance(value, str):
        items = re.split(r"[,\s]+", value.strip().strip("[]"))
    elif isinstance(value, list):
        items = [str(item) for item in value]
    else:
        return []
    return [item.strip().strip("'\"") for item in items if item and item.strip().strip("'\"")]


def _requirements(front: dict[str, Any]) -> dict[str, list[str]]:
    tools = _string_list(front.get("allowed-tools"))
    bins: set[str] = set()
    env: set[str] = set()
    metadata = front.get("metadata") if isinstance(front.get("metadata"), dict) else {}
    blocks = [metadata, *(metadata.get(host) for host in ("clawdbot", "openclaw") if isinstance(metadata.get(host), dict))]
    for block in blocks:
        requires = block.get("requires") if isinstance(block.get("requires"), dict) else {}
        bins.update(_string_list(requires.get("bins")))
        env.update(name for name in _string_list(requires.get("env")) if ENV_NAME_RE.match(name))
        primary = str(block.get("primaryEnv") or "")
        if ENV_NAME_RE.match(primary):
            env.add(primary)
    env.update(name for name in _string_list(front.get("secrets")) if ENV_NAME_RE.match(name))
    return {"tools": tools, "bins": sorted(bins), "env": sorted(env)}


def _license_file_kind(folder: Path) -> str | None:
    """What a LICENSE file's opening says, when the frontmatter says nothing."""
    for name in LICENSE_FILES:
        path = folder / name
        if not path.is_file():
            continue
        try:
            with path.open("r", encoding="utf-8", errors="replace") as handle:
                head = " ".join(handle.read(400).split())
        except OSError:
            continue
        if RESTRICTIVE_LICENSE_RE.search(head):
            return "restricted"
        if re.match(r"^(the )?mit license\b", head, re.IGNORECASE) or re.search(r"apache license,? version 2\.0", head, re.IGNORECASE):
            return "permissive"
    return None


def _license(front: dict[str, Any], folder: Path) -> dict[str, Any]:
    declared = str(front.get("license") or "").strip()
    has_file = any((folder / name).is_file() for name in LICENSE_FILES)
    if declared and RESTRICTIVE_LICENSE_RE.search(declared):
        kind = "restricted"
    elif declared.lower() in PERMISSIVE_LICENSES:
        kind = "permissive"
    elif not declared and has_file:
        kind = _license_file_kind(folder) or "unknown"
    else:
        kind = "unknown"
    return {"declared": declared or None, "file": has_file, "class": kind}


def _walk_skill(folder: Path) -> tuple[list[str], int, list[str], bool]:
    bundles = sorted(name for name in SKILL_BUNDLE_DIRS if (folder / name).is_dir())
    manifests = sorted(name for name in DEPENDENCY_MANIFESTS if (folder / name).is_file())
    code_files = 0
    seen = 0
    truncated = False
    for current, dirnames, filenames in os.walk(folder, followlinks=False):
        dirnames[:] = sorted(d for d in dirnames if not _is_link(Path(current) / d) and d not in {"node_modules", ".git"})
        for filename in filenames:
            seen += 1
            if seen > MAX_FILES_PER_SKILL:
                truncated = True
                break
            if Path(filename).suffix.lower() in CODE_SUFFIXES:
                code_files += 1
        if truncated:
            break
    return bundles, code_files, manifests, truncated


def scan_skill(folder: Path, library_root: Path) -> dict[str, Any]:
    """One skill folder as catalog metadata.  Reads; never copies a body."""
    skill_md = folder / "SKILL.md"
    raw = skill_md.read_bytes()
    front = _frontmatter(raw.decode("utf-8", errors="replace")) or {}
    meta: dict[str, Any] = {}
    meta_path = folder / "_skillhub_meta.json"
    if meta_path.is_file():
        try:
            loaded = json.loads(meta_path.read_text(encoding="utf-8"))
            meta = loaded if isinstance(loaded, dict) else {}
        except (OSError, ValueError):
            meta = {}
    bundles, code_files, manifests, truncated = _walk_skill(folder)
    paid = str(front.get("pricing") or "").lower() == "paid" or bool(front.get("x402"))
    pricing: dict[str, Any] = {"paid": paid}
    if paid:
        if front.get("price_hint"):
            pricing["price_hint"] = str(front["price_hint"])
        if front.get("x402_protocol"):
            pricing["protocol"] = str(front["x402_protocol"])
    name = front.get("display_name") or front.get("displayName") or meta.get("name") or front.get("name") or folder.name
    entry: dict[str, Any] = {
        "id": folder.name,
        "name": str(name),
        "name_en": str(front.get("display_name_en") or ""),
        "version": str(front.get("version") or meta.get("version") or ""),
        "category": re.sub(r"^\d+-", "", folder.parent.name),
        "summary": _summary(front.get("description_zh") or front.get("description") or front.get("summary") or meta.get("description_zh")),
        "source": {
            "path": folder.relative_to(library_root).as_posix(),
            "marketplace_id": str(meta.get("skillId") or ""),
            "skill_md_sha256": hashlib.sha256(raw).hexdigest(),
        },
        "frontmatter": bool(front),
        "agent_created": str(front.get("agent_created")).lower() == "true",
        "requires": _requirements(front),
        "bundles": bundles,
        "code_files": code_files,
        "dependency_manifests": manifests,
        "license": _license(front, folder),
        "pricing": pricing,
    }
    if truncated:
        entry["file_walk_truncated"] = True
    return entry


def scan_skill_library(root: Path) -> list[dict[str, Any]]:
    """Every ``<category>/<skill>/SKILL.md`` under ``root``, sorted.

    Two levels and no further: links and junctions are not followed, and
    nothing outside ``root`` is read.
    """
    root = root.resolve()
    entries: list[dict[str, Any]] = []
    for category in sorted(root.iterdir()):
        if not category.is_dir() or _is_link(category) or category.name.startswith("."):
            continue
        for folder in sorted(category.iterdir()):
            # The exact name: on a case-insensitive disk skill.md answers to SKILL.md, and the import would refuse it.
            if folder.is_dir() and not _is_link(folder) and (folder / "SKILL.md").is_file() and "SKILL.md" in {child.name for child in folder.iterdir()}:
                entries.append(scan_skill(folder, root))
    # The library's own order (its numbered category folders), not the alphabet.
    return sorted(entries, key=lambda entry: entry["source"]["path"])


