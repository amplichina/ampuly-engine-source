@dataclass
class ComponentCatalog:
    connectors: list[dict[str, Any]] = field(default_factory=list)
    domains: list[dict[str, Any]] = field(default_factory=list)
    tooling: list[dict[str, Any]] = field(default_factory=list)
    planned: list[dict[str, Any]] = field(default_factory=list)
    skills: list[dict[str, Any]] = field(default_factory=list)
    problems: list[str] = field(default_factory=list)
    # The local resource library the skills were scanned from (its folder name), as skills.yaml records it.
    library: str = ""

    def to_payload(self) -> dict[str, Any]:
        categories = list(dict.fromkeys(str(skill["category"]) for skill in self.skills if skill.get("category")))
        return {
            "domains": self.domains,
            "connectors": [connector_payload(entry) for entry in self.connectors],
            "tooling": self.tooling,
            "planned": self.planned,
            "skills": [skill_payload(entry) for entry in self.skills],
            "skill_categories": categories,
            "problems": list(self.problems),
        }


