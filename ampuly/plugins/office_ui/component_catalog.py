"""组件库目录: the connectors and skills the builder may *offer*.

A catalog entry is a candidate, never an enabled capability.  Nothing in this
module installs, starts or calls anything: an entry reaches a workflow node
only after its own admission (the governance rules' five questions for a
connector, a license and code review for a skill).  What lives here is the
metadata a person needs to choose a component and see its risk before that.

Two files under ``distribution/component_catalog/``:

* ``connectors.yaml`` -- migrated by hand from the owner's connector list.
  Hand-authored, so it is validated strictly: a risk level must follow from
  the reasons given, a credential-shaped config key must be marked secret,
  and a source path must be relative to the library, never a machine path.
* ``skills.yaml`` -- generated by ``scripts/build_component_catalog.py`` from
  a local skill library.  Metadata only: no skill body, script or example is
  copied, and the risk is derived here from what the skill declares, so the
  generator and the loader cannot disagree about it.
"""

