"""内置运行时的物料清单：从已安装的环境读出来，写成可审阅、可比对的文件。

规划 W15 / §19：最小发行包要有内置开源运行时的版本、许可证与 SBOM。发行包
（`distribution/releases`）已有自己的 SBOM；**运行时**这一层——受管 Codex SDK、
内置二进制、协议桥依赖——没有。这个脚本补这一层，不联网、不安装、不改环境：

    .venv/Scripts/python scripts/runtime_sbom.py write    # 写 distribution/runtime/superones-runtime.sbom.json
    .venv/Scripts/python scripts/runtime_sbom.py check    # 与已提交的文件比对，漂移即非零退出

记录的每一项：名称、版本、许可证（包元数据）、pip 记录的文件数与其 RECORD 摘要
（所有已安装文件的路径+哈希再哈希，包被换过就变）、直接依赖声明；另加内置
`codex.exe` 的 SHA256 与大小；Computer Use 还记录 `playwright install chromium`
实际需要的 Chromium、headless shell、FFmpeg 和平台辅助物料闭包。不记录任何
本机缓存路径，也不记录密钥。
`check` 是给门禁用的：`tests/test_runtime_sbom.py` 会跑它，所以升级依赖必须同时
更新这个文件——这就是「升级需要测试」在仓库里的形状。
"""

from __future__ import annotations

import argparse
import hashlib
import json
import platform
import sys
from datetime import datetime
from importlib import metadata
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO))

OUTPUT = REPO / "distribution" / "runtime" / "superones-runtime.sbom.json"
# The runtime profile in pyproject plus the converter the bridge pins.
RUNTIME_DISTRIBUTIONS = ("openai-codex", "openai-codex-cli-bin", "openai", "aiohttp", "lark", "litellm")
# Fields that change between two identical installs and must not count as drift.
VOLATILE = {"generated_at", "python"}


def _license(dist: metadata.Distribution) -> str:
    declared = str(dist.metadata.get("License", "") or "").strip()
    if declared and len(declared) <= 80:
        return declared
    classifiers = [c for c in dist.metadata.get_all("Classifier", []) or [] if c.startswith("License ::")]
    if classifiers:
        return classifiers[0].split("::")[-1].strip()
    expression = str(dist.metadata.get("License-Expression", "") or "").strip()
    return expression or "unknown"


# Written by the installer about *how* a distribution got here, not what it
# is: pip adds REQUESTED when a package was asked for by name, direct_url.json
# when it came from a URL or a local wheel, INSTALLER always. A fresh machine
# installing the same wheel from the index has a different set of these (V4,
# 2026-09-12: every component drifted by exactly one such file), so they are
# not part of the content digest.
INSTALLER_METADATA = frozenset({"REQUESTED", "INSTALLER", "direct_url.json", "RECORD"})


def _record_digest(dist: metadata.Distribution) -> tuple[int, str]:
    """One hash over pip's RECORD: path and hash of every installed file, installer notes aside."""
    entries: list[str] = []
    for item in dist.files or []:
        parts = item.parts
        # Bytecode is generated by importing the package, not shipped by the
        # wheel; counting it made every test run a new "drift".
        if "__pycache__" in parts or item.suffix == ".pyc":
            continue
        if len(parts) >= 2 and parts[-2].endswith(".dist-info") and parts[-1] in INSTALLER_METADATA:
            continue
        if parts and parts[0] == "..":
            # Outside site-packages: console-script launchers, which pip
            # generates per environment with the interpreter path inside
            # (`../../Scripts/litellm.exe` hashed differently on the fresh
            # machine). Generated here, not shipped by the wheel.
            continue
        entries.append(f"{item.as_posix()} {item.hash.value if item.hash else ''}")
    entries.sort()
    return len(entries), hashlib.sha256("\n".join(entries).encode("utf-8")).hexdigest()


def _component(name: str) -> dict[str, Any]:
    dist = metadata.distribution(name)
    count, digest = _record_digest(dist)
    requires = sorted(str(r).split(";")[0].strip() for r in (dist.requires or []) if "extra ==" not in str(r))
    return {
        "name": name,
        "version": dist.version,
        "license": _license(dist),
        "installed_files": count,
        "record_sha256": digest,
        "requires": requires,
    }


def _bundled_binary() -> dict[str, Any]:
    from codex_cli_bin import bundled_codex_path

    path = Path(str(bundled_codex_path()))
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1 << 20), b""):
            digest.update(chunk)
    return {"name": path.name, "size_bytes": path.stat().st_size, "sha256": digest.hexdigest(),
            "source": "openai-codex-cli-bin wheel", "license": "Apache-2.0"}


def _computer_use() -> dict[str, Any]:
    """4.3 X12: the Computer Use executor is part of the bill -- the Playwright package, the Chromium
    build its driver manifest names (downloaded at install, launched at run time), and the vision
    grammar's digest. A change in any of them is drift here and a different combination in the
    evidence ledger (G11)."""
    from ampuly.computer_use.combination import browser_build, current_combination

    build = browser_build()
    # ``playwright install chromium`` is not one directory.  On Windows it
    # installs the headed browser, headless shell, ffmpeg and winldd.  Naming
    # only Chromium made the old SBOM truthful about the version but
    # incomplete as an offline-install bill of materials.  Read the registry
    # shipped by this exact Playwright wheel; do not inspect or download a
    # user cache here.
    import playwright

    registry_path = Path(playwright.__file__).resolve().parent / "driver" / "package" / "browsers.json"
    registry = json.loads(registry_path.read_text(encoding="utf-8"))
    wanted = {"chromium", "chromium-headless-shell", "ffmpeg"}
    if platform.system().lower() == "windows":
        wanted.add("winldd")
    closure: list[dict[str, Any]] = []
    for entry in registry.get("browsers", []):
        name = str(entry.get("name", ""))
        if name not in wanted:
            continue
        closure.append({
            "name": name,
            "revision": str(entry.get("revision", "")),
            "version": str(entry.get("browserVersion", "") or ""),
            "directory": f"{name.replace('-', '_')}-{entry.get('revision', '')}",
        })
    return {
        "playwright": _component("playwright") if build["playwright"] != "absent" else {"name": "playwright", "version": "absent"},
        "browsers": [{"name": "chromium", "revision": build["chromium_revision"], "version": build["chromium_version"],
                      "source": "playwright driver manifest (browsers.json); fetched by `playwright install`, not shipped in the wheel"}],
        "browser_install_closure": closure,
        "vision_grammar": current_combination(acting_model="").vision_grammar,
    }


def build() -> dict[str, Any]:
    return {
        "schema": "superones-runtime-sbom/1",
        "generated_at": datetime.now().isoformat(timespec="seconds"),
        "python": f"{sys.version_info.major}.{sys.version_info.minor}",
        "profile": "superones-runtime",
        "components": [_component(name) for name in RUNTIME_DISTRIBUTIONS],
        "bundled_binary": _bundled_binary(),
        "computer_use": _computer_use(),
    }


def _stable(payload: dict[str, Any]) -> dict[str, Any]:
    return {k: v for k, v in payload.items() if k not in VOLATILE}


def write(path: Path = OUTPUT) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(build(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8", newline="\n")
    return path


def check(path: Path = OUTPUT) -> list[str]:
    """Differences between the committed file and this environment, by name."""
    if not path.is_file():
        return [f"missing: {path}"]
    try:
        recorded = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return [f"unreadable: {type(exc).__name__}"]
    current = build()
    problems: list[str] = []
    if _stable(recorded).get("schema") != current["schema"]:
        problems.append("schema changed")
    old = {c["name"]: c for c in recorded.get("components", []) if isinstance(c, dict)}
    for component in current["components"]:
        before = old.get(component["name"])
        if before is None:
            problems.append(f"{component['name']}: not in the committed SBOM")
            continue
        for key in ("version", "license", "installed_files", "record_sha256", "requires"):
            if before.get(key) != component[key]:
                problems.append(f"{component['name']}: {key} changed ({before.get(key)!r} -> {component[key]!r})")
    for extra in set(old) - {c["name"] for c in current["components"]}:
        problems.append(f"{extra}: in the committed SBOM but not a runtime component")
    binary = recorded.get("bundled_binary", {})
    for key in ("name", "size_bytes", "sha256"):
        if binary.get(key) != current["bundled_binary"][key]:
            problems.append(f"bundled binary: {key} changed")
    recorded_cu = recorded.get("computer_use")
    if not isinstance(recorded_cu, dict):
        problems.append("computer_use: not in the committed SBOM")
        return problems
    current_cu = current["computer_use"]
    for key in ("version", "license", "installed_files", "record_sha256"):
        if recorded_cu.get("playwright", {}).get(key) != current_cu["playwright"].get(key):
            problems.append(f"playwright: {key} changed ({recorded_cu.get('playwright', {}).get(key)!r} -> {current_cu['playwright'].get(key)!r})")
    if recorded_cu.get("browsers") != current_cu["browsers"]:
        problems.append(f"browsers changed ({recorded_cu.get('browsers')!r} -> {current_cu['browsers']!r})")
    if recorded_cu.get("browser_install_closure") != current_cu["browser_install_closure"]:
        problems.append("browser install closure changed")
    if recorded_cu.get("vision_grammar") != current_cu["vision_grammar"]:
        problems.append("vision grammar changed")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("command", choices=("write", "check"))
    parser.add_argument("--path", default=str(OUTPUT))
    args = parser.parse_args()
    path = Path(args.path)
    if args.command == "write":
        print(f"wrote {write(path)}")
        return 0
    problems = check(path)
    for line in problems:
        print(f"drift: {line}")
    print("runtime SBOM: OK" if not problems else f"runtime SBOM: {len(problems)} difference(s); regenerate with `write` after reviewing the upgrade")
    return 0 if not problems else 1


if __name__ == "__main__":
    raise SystemExit(main())
